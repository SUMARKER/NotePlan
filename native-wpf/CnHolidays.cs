        /// <summary>查询某天的节假日信息；无则返回 null。</summary>
        public static (string Name, bool Off)? Get(DateTime date)
        {
            if (!Data.TryGetValue(date.Year, out var days)) return null;
            var md = date.ToString("MM-dd");
            foreach (var d in days)
                if (d.Md == md) return (d.Name, d.Off);
            return null;
        }
